import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const canonicalRoot = fileURLToPath(new URL("../../../apps/desktop/src/features/document/", import.meta.url));
const output = fileURLToPath(new URL("../src/types.ts", import.meta.url));
const program = ts.createProgram([
  path.join(canonicalRoot, "model/index.ts"),
  path.join(canonicalRoot, "overlay-model.ts"),
], {
  target: ts.ScriptTarget.ES2021, module: ts.ModuleKind.ESNext,
  moduleResolution: ts.ModuleResolutionKind.Bundler,
  declaration: true, emitDeclarationOnly: true, skipLibCheck: true, strict: true,
});
const declarations = new Map();
const result = program.emit(undefined, (name, source) => {
  if (name.endsWith(".d.ts")) declarations.set(name, source);
});
const errors = [...ts.getPreEmitDiagnostics(program), ...result.diagnostics]
  .filter((diagnostic) => diagnostic.category === ts.DiagnosticCategory.Error);
if (errors.length) throw new Error(ts.formatDiagnosticsWithColorAndContext(errors, {
  getCanonicalFileName: (name) => name, getCurrentDirectory: () => process.cwd(), getNewLine: () => "\n",
}));
const printer = ts.createPrinter();
const chunks = [];
for (const [name, source] of [...declarations].sort(([a], [b]) => a.localeCompare(b))) {
  const file = ts.createSourceFile(name, source, ts.ScriptTarget.Latest, true);
  for (const node of file.statements) {
    if (ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) continue;
    // Keep private base types too: exported shapes inherit their properties.
    chunks.push(printer.printNode(ts.EmitHint.Unspecified, node, file));
  }
}
const generated = "// Generated by scripts/generate-document-types.mjs from features/document. Do not edit.\n\n" + chunks.join("\n\n") + "\n";
const files = new Map([
  [output, generated],
  [fileURLToPath(new URL("../src/overlay-types.ts", import.meta.url)), '// Compatibility entrypoint; declarations are generated from the canonical model.\nexport type * from "./types.js";\n'],
  [fileURLToPath(new URL("../src/graph3d-types.ts", import.meta.url)), '// Compatibility entrypoint; declarations are generated from the canonical model.\nexport type * from "./types.js";\n'],
]);
for (const [name, content] of files) {
  if (process.argv.includes("--check")) {
    if (await readFile(name, "utf8") !== content) throw new Error(`Stale generated declarations: ${name}`);
  } else await writeFile(name, content);
}
